export type IconName = keyof typeof ART;

const pathCache = new Map<IconName, string>();

export function iconPath(name: IconName): string {
  const cached = pathCache.get(name);
  if (cached !== undefined) {
    return cached;
  }
  const path = pixelPath(ART[name], INK);
  pathCache.set(name, path);
  return path;
}

